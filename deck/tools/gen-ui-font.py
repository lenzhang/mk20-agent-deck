#!/usr/bin/env python3
"""Offline font asset generation only. Runtime/tests need neither Pillow nor fonts.

Reference invocation (Pillow 13.0.0, FreeType 2.14.3):
 python3 gen-ui-font.py --font /path/to/NotoSansSC-Regular.otf \
     --ascii-font /path/to/DejaVuSansMono.ttf
Glyphs use fixed 8/16 x16 cells, threshold 96; icons are original pixels.
Pass --check with the SAME font/rasterizer to verify reproducibility.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, __version__
from PIL import features
ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser()
ap.add_argument('--font', required=True, help='Noto Sans SC Regular (SIL Open Font License 1.1)')
ap.add_argument('--ascii-font', required=True, help='DejaVuSansMono.ttf (Bitstream Vera/DejaVu license)')
ap.add_argument('--check', action='store_true')
a = ap.parse_args()
source = Path(a.font)
font = ImageFont.truetype(str(source), 14)
ascii_source = Path(a.ascii_font)
ascii_font = ImageFont.truetype(str(ascii_source), 13)
strings = []
for path in [ROOT/'kbd/ui_labels.inc', ROOT/'kbd/ui.c', ROOT/'kbd/providers.inc']:
    strings += [json.loads(s) for s in re.findall(r'"(?:[^"\\]|\\.)*"', path.read_text())]
cps = sorted(set(range(32,127)) | {ord(c) for s in strings for c in s if ord(c)>=32} | {0xfffd})
# Original explicit rotation, check, ellipsis, stop, PTT and replacement glyphs.
icons = {
 0x27f2: ['   #####','  #     #',' #       #',' #','###',' #       #','  #     #','   #####'],
 0x27f3: ['   #####','  #     #',' #       #','         #','        ###',' #       #','  #     #','   #####'],
 0x2713: ['          #','         ##','        ##',' #     ##',' ##   ##','  ## ##','   ###','    #'],
 0x2026: ['','','','','','','',' ##   ##   ##',' ##   ##   ##'],
 0x23f9: ['##########']*10,
 0x1f399: ['    ####','   #    #','   #    #','   #    #','   #    #',' # #    # #',' #  ####  #','  #      #','   ######','     ##','   ######'],
 0xfffd: ['     #','    # #','   # # #','  #   # #',' #   #   #','  #  #  #','   #   #','    # #','     #']}
rows = [f'''/* Generated by tools/gen-ui-font.py; do not edit.
 * Source: {source.name}, SHA256 {hashlib.sha256(source.read_bytes()).hexdigest()}.
 * Source license: SIL Open Font License 1.1; see font-LICENSE-NotoSansSC.txt.
 * No font binary is shipped; these are fixed raster strikes derived from the source.
 * ASCII source: DejaVuSansMono.ttf, SHA256 {hashlib.sha256(ascii_source.read_bytes()).hexdigest()}.
 * ASCII license: Bitstream Vera/DejaVu, see font-LICENSE-DejaVu.txt.
 * These fixed raster strikes are derived glyph images; no runtime font fallback.
 * Icons/replacement: original MK20 pixel drawings, same license as this code.
 * Rasterizer: Pillow {__version__}, FreeType {features.version_module('freetype2')}; face 0,
 * CJK 14 px / ASCII 13 px, horizontal bbox centering, baseline origin y=0;
 * threshold >=96, 8/16x16, MSB-left uint16 rows.
 */''', '#include "ui_font.h"', 'const ui_glyph_t UI_GLYPHS[] = {']
for cp in cps:
    w = 8 if cp<127 else 16
    im = Image.new('L',(w,16)); draw=ImageDraw.Draw(im)
    if cp in icons:
        for y,line in enumerate(icons[cp]):
            for x,pixel in enumerate(line):
                if pixel=='#': im.putpixel((x+1,y+2),255)
    else:
        f = ascii_font if cp<127 else font
        bbox=f.getbbox(chr(cp)); x=(w-(bbox[2]-bbox[0]))//2-bbox[0]
        draw.text((x,0),chr(cp),font=f,fill=255)
    bits=[sum(1<<(15-x) for x in range(w) if im.getpixel((x,y))>=96) for y in range(16)]
    if cp!=32 and not any(bits): raise SystemExit(f'empty glyph U+{cp:04X}')
    rows.append('    {0x%x, %d, {%s}},' % (cp,w,','.join('0x%04x'%b for b in bits)))
rows+=['};','const size_t UI_GLYPH_COUNT = sizeof UI_GLYPHS / sizeof UI_GLYPHS[0];','']
out='\n'.join(rows); path=ROOT/'kbd/ui_font.c'
if a.check:
    if path.read_text()!=out: raise SystemExit('ui_font.c stale (font/rasterizer must match)')
else: path.write_text(out)
